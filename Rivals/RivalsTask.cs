using System.Collections.Generic;
using System.Linq;

namespace Rivals
{
    /// <summary>
    /// Класс для разделения карты между охотниками за сокровищами
    /// </summary>
    public class RivalsTask
    {
        /// <summary>
        /// Определяет, какие клетки карты достанутся каждому охотнику
        /// </summary>
        /// <param name="map">Карта с препятствиями, игроками и сундуками</param>
        /// <returns>Коллекция занятых клеток с указанием владельца и расстояния</returns>
        /// <remarks>
        /// Алгоритм:
        /// 1. Каждый игрок начинает со своей стартовой позиции (расстояние 0)
        /// 2. Поиск в ширину (BFS) распространяется от всех игроков одновременно
        /// 3. Клетка достаётся тому игроку, который первым до неё добрался
        /// 4. Клетки с сундуками можно занять, но из них нельзя распространяться дальше
        /// </remarks>
        public static IEnumerable<OwnedLocation> AssignOwners(Map map)
        {
            // ================================================================
            // ОЧЕРЕДЬ ДЛЯ BFS
            // ================================================================
            // Хранит: (точка, номер игрока, расстояние от старта)
            // Используем Queue (FIFO) для обхода в ширину
            var queue = new Queue<(Point point, int player, int distance)>();

            // ================================================================
            // СЛОВАРЬ ЗАНЯТЫХ КЛЕТОК
            // ================================================================
            // Ключ: координаты точки
            // Значение: (номер игрока, расстояние)
            // Позволяет быстро проверить, занята ли клетка, и кем
            var owner = new Dictionary<Point, (int player, int distance)>();

            // ================================================================
            // ШАГ 1: ИНИЦИАЛИЗАЦИЯ
            // ================================================================
            // Каждый игрок начинает со своей стартовой точки
            // Расстояние 0, игрок владеет своей стартовой клеткой
            for (int i = 0; i < map.Players.Length; i++)
            {
                var start = map.Players[i];

                // Добавляем в очередь для дальнейшего распространения
                queue.Enqueue((start, i, 0));

                // Отмечаем клетку как занятую этим игроком
                owner[start] = (i, 0);

                // Возвращаем результат (лениво, через yield)
                yield return new OwnedLocation(i, start, 0);
            }

            // ================================================================
            // ШАГ 2: ОСНОВНОЙ ЦИКЛ BFS
            // ================================================================
            // Пока есть клетки для обработки
            while (queue.Count > 0)
            {
                // Извлекаем следующую клетку из очереди
                var (current, player, dist) = queue.Dequeue();

                // ============================================================
                // ПРОВЕРКА АКТУАЛЬНОСТИ ЗАПИСИ
                // ============================================================
                // В очереди могут быть устаревшие записи.
                // Например: игрок 0 дошёл до клетки A на расстоянии 5,
                // но игрок 1 уже занял её на расстоянии 4.
                // Проверяем, совпадает ли текущая запись с владельцем в словаре.
                if (!owner.TryGetValue(current, out var currentOwner) ||
                    currentOwner.player != player ||
                    currentOwner.distance != dist)
                    // Запись устарела — пропускаем
                    continue;

                // ============================================================
                // ПРОВЕРКА НА СУНДУК
                // ============================================================
                // Если в этой клетке есть сундук, игрок может её занять,
                // но дальше из этой клетки распространяться НЕЛЬЗЯ.
                // Поэтому просто пропускаем добавление соседей.
                if (map.Chests.Contains(current))
                    continue;  // Не добавляем соседей

                // ============================================================
                // ДОБАВЛЕНИЕ СОСЕДЕЙ
                // ============================================================
                // Проверяем всех четырёх соседей (вверх, вниз, влево, вправо)
                foreach (var neighbor in GetNeighbors(map, current))
                {
                    // Если соседняя клетка уже занята — пропускаем
                    if (owner.ContainsKey(neighbor))
                        continue;

                    // Занимаем клетку текущим игроком
                    // Расстояние = текущее расстояние + 1
                    owner[neighbor] = (player, dist + 1);

                    // Добавляем клетку в очередь для дальнейшего распространения
                    queue.Enqueue((neighbor, player, dist + 1));

                    // Возвращаем результат
                    yield return new OwnedLocation(player, neighbor, dist + 1);
                }
            }
            // Цикл завершается, когда очередь пуста — все достижимые клетки заняты
        }

        /// <summary>
        /// Возвращает все допустимые соседние клетки для заданной точки
        /// </summary>
        /// <param name="map">Карта для проверки границ и стен</param>
        /// <param name="point">Точка, от которой ищем соседей</param>
        /// <returns>Последовательность соседних клеток (вверх, вниз, влево, вправо)</returns>
        private static IEnumerable<Point> GetNeighbors(Map map, Point point)
        {
            // Четыре направления движения
            var directions = new[]
            {
                new Point(0, -1), // вверх (Y уменьшается)
                new Point(0, 1),  // вниз  (Y увеличивается)
                new Point(-1, 0), // влево (X уменьшается)
                new Point(1, 0)   // вправо (X увеличивается)
            };

            foreach (var dir in directions)
            {
                // Вычисляем координаты соседа
                var neighbor = new Point(point.X + dir.X, point.Y + dir.Y);

                // Проверка 1: не выходит ли сосед за границы карты
                // Проверка 2: не является ли сосед стеной (MapCell.Wall)
                if (map.InBounds(neighbor) && map.Maze[neighbor.X, neighbor.Y] != MapCell.Wall)
                    yield return neighbor;  // Сосед проходим — возвращаем
            }
        }
    }
}